#!/usr/bin/env bash
# Writes procedural_filters.js, beside this script, from Brave's
# content_cosmetic.ts and procedural_filters.ts.
#
#   nix develop .#full --command \
#     ./packages/domicile-engine/src/components/domicile/renderer/procedural_filters/bundle.sh
#
# The engine's build has no bun, so the bundle is checked in and its sources
# are not: both are brave-core's components/cosmetic_filters/resources/data,
# unchanged, at the revision below (Brave 1.102.41), checked by sha256.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$HERE/procedural_filters.js"
REVISION=c421330788f099d194ab61f52e3c0e0410fd4156
BASE="https://raw.githubusercontent.com/brave/brave-core/$REVISION/components/cosmetic_filters/resources/data"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

while read -r file sum; do
  curl -sSfL -o "$WORK/$file" "$BASE/$file"
  got="$(sha256sum <"$WORK/$file" | cut -d' ' -f1)"
  [ "$got" = "$sum" ] || {
    echo "bundle.sh: $file has sha256 $got, not $sum" >&2
    exit 1
  }
done <<'SUMS'
content_cosmetic.ts 41c822529d398ef0f862b3f7dc6a802346c08020f6222c876a32e6e8db35aa59
procedural_filters.ts 85a6545f0138127eb86bd5a9ac1d5c852c3c74f34b75d9414c153b199de97c6b
SUMS

(cd "$WORK" && bun build content_cosmetic.ts --target=browser --format=iife \
  --outfile="$WORK/bundle.js" >/dev/null)
{
  cat <<'HEADER'
// Copyright (c) 2020 The Brave Authors. All rights reserved.
// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this file,
// You can obtain one at https://mozilla.org/MPL/2.0/.
//
// Generated by bundle.sh from content_cosmetic.ts and procedural_filters.ts.
// Do not edit; change those and run it.
HEADER
  cat "$WORK/bundle.js"
} >"$OUT"
echo "wrote $OUT"
