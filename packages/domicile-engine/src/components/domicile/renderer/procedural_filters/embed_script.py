"""Writes a script into a C++ header as one string constant.

  embed_script.py SCRIPT HEADER NAME
"""

import sys

DELIMITER = "js"


def main(script, header, name):
    with open(script, encoding="utf-8") as source:
        text = source.read()
    if ")%s\"" % DELIMITER in text:
        sys.exit("%s holds )%s\", which ends the raw string" % (script, DELIMITER))
    guard = header.upper().replace("/", "_").replace(".", "_").replace("-", "_")
    with open(header, "w", encoding="utf-8") as out:
        out.write("// Generated by embed_script.py from %s. Do not edit.\n" % script)
        out.write("#ifndef %s_\n#define %s_\n\n" % (guard, guard))
        out.write('inline constexpr char %s[] = R"%s(' % (name, DELIMITER))
        out.write(text)
        out.write(')%s";\n\n#endif\n' % DELIMITER)


if __name__ == "__main__":
    main(*sys.argv[1:4])
