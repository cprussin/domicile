// Writes `src/zone-coordinates.ts` from the tz database: each time zone's
// principal city, so night light finds sunset without asking for a location.
//
//   bun scripts/zone-coordinates.ts /usr/share/zoneinfo

const [zoneinfo] = process.argv.slice(2);
if (zoneinfo === undefined) {
  throw new Error("usage: bun scripts/zone-coordinates.ts <zoneinfo dir>");
}

const lines = async (name: string): Promise<string[]> =>
  (await Bun.file(`${zoneinfo}/${name}`).text())
    .split("\n")
    .filter((line) => line !== "" && !line.startsWith("#"));

/** `+DDMM[SS]` or `+DDDMM[SS]` as degrees. */
const degrees = (text: string, degreeDigits: number): number => {
  const sign = text.startsWith("-") ? -1 : 1;
  const digits = text.slice(1);
  const whole = Number(digits.slice(0, degreeDigits));
  const minutes = Number(digits.slice(degreeDigits, degreeDigits + 2));
  const seconds = Number(digits.slice(degreeDigits + 2) || "0");
  return sign * (whole + minutes / 60 + seconds / 3600);
};

const COORDINATES = /^([+-]\d{4,6})([+-]\d{5,7})$/;

const located = (line: string): [string, [number, number]] => {
  const [, coordinates = "", zone = ""] = line.split("\t");
  const [, latitude = "", longitude = ""] = COORDINATES.exec(coordinates) ?? [];
  return [
    zone,
    [
      Math.round(degrees(latitude, 2) * 10) / 10,
      Math.round(degrees(longitude, 3) * 10) / 10,
    ],
  ];
};

const zones = new Map(
  [...(await lines("zone.tab")), ...(await lines("zone1970.tab"))].map(located),
);
const links = (await lines("tzdata.zi"))
  .filter((line) => line.startsWith("L "))
  .map((line) => line.split(" ").slice(1))
  .flatMap(([target = "", link = ""]) => {
    const found = zones.get(target);
    return found === undefined ? [] : [[link, found] as const];
  });
const all = new Map([...zones, ...links]);

const entries = [...all]
  .sort(([a], [b]) => (a < b ? -1 : 1))
  .map(
    ([zone, [latitude, longitude]]) =>
      `  "${zone}": [${latitude}, ${longitude}],`,
  )
  .join("\n");

await Bun.write(
  new URL("../src/zone-coordinates.ts", import.meta.url),
  `// Generated by scripts/zone-coordinates.ts from the tz database. Do not edit.

/** Each time zone's principal city, as [latitude, longitude] in degrees. */
export const ZONE_COORDINATES: Readonly<
  Record<string, readonly [number, number]>
> = {
${entries}
};
`,
);
