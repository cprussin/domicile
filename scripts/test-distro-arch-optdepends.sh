#!/usr/bin/env bash
# Tests `distro/arch-optdepends.sh`, which adds the `optdepend` lines nfpm
# cannot write to an Arch package.
#
# Builds a package laid out as nfpm lays one out, adds optional dependencies,
# and checks the package's metadata and files.
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OPTDEPENDS_SH="$ROOT/distro/arch-optdepends.sh"
[ -x "$OPTDEPENDS_SH" ] || { echo "no $OPTDEPENDS_SH" >&2; exit 1; }

for tool in tar zstd gzip md5sum sha256sum; do
  command -v "$tool" >/dev/null 2>&1 || { echo "  SKIP: no $tool"; exit 77; }
done

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

FAILED=0
ok() { printf '  ok    %s\n' "$1"; }
fail() {
  printf '  FAIL  %s\n    %s\n' "$1" "$2"
  FAILED=$((FAILED + 1))
}
expect() { # what, want, got
  if [ "$3" = "$2" ]; then
    ok "$1"
  else
    fail "$1" "wanted: $(printf '%q' "$2")  got: $(printf '%q' "$3")"
  fi
}

# ---- a package as nfpm makes one -------------------------------------------

TREE="$WORK/tree"
mkdir -p "$TREE/usr/bin"
printf '#!/bin/sh\n' >"$TREE/usr/bin/domicile"
chmod 755 "$TREE/usr/bin/domicile"
printf '%s\n' '# Generated by nfpm' 'pkgname = domicile' 'pkgver = 0.1-1' \
  'depend = glibc>=2.34' >"$TREE/.PKGINFO"
mtree_line() { # path
  printf './%s time=1.0 mode=%s size=%s type=file md5digest=%s sha256digest=%s\n' \
    "$1" "$(stat -c %a "$TREE/$1")" "$(stat -c %s "$TREE/$1")" \
    "$(md5sum <"$TREE/$1" | cut -d' ' -f1)" "$(sha256sum <"$TREE/$1" | cut -d' ' -f1)"
}
{
  echo '#mtree'
  mtree_line .PKGINFO
  echo './usr/ time=1.0 mode=755 type=dir'
  echo './usr/bin/ time=1.0 mode=755 type=dir'
  mtree_line usr/bin/domicile
} | gzip -n >"$TREE/.MTREE"
# nfpm writes the install script after the metadata.
printf 'post_install() {\n  :\n}\n' >"$TREE/.INSTALL"
PACKAGE="$WORK/domicile-0.1-1-x86_64.pkg.tar.zst"
tar -C "$TREE" --owner=0 --group=0 --numeric-owner --no-recursion --zstd -cf "$PACKAGE" \
  usr/ usr/bin/ usr/bin/domicile .PKGINFO .MTREE .INSTALL

cat >"$WORK/optdepends" <<'LIST'
# Comments and blank lines are skipped.

upower: the battery readout
curl: bookmark icons
LIST

# ---- adding the optional dependencies --------------------------------------

echo "optional dependencies are added"
if out="$("$OPTDEPENDS_SH" "$PACKAGE" "$WORK/optdepends" 2>&1)"; then
  ok "arch-optdepends.sh succeeds"
else
  fail "arch-optdepends.sh succeeds" "$out"
fi

OUT="$WORK/out"
mkdir -p "$OUT"
tar -C "$OUT" --zstd -xf "$PACKAGE"
expect ".PKGINFO lists them after what nfpm wrote" \
  "$(printf '%s\n' '# Generated by nfpm' 'pkgname = domicile' 'pkgver = 0.1-1' \
    'depend = glibc>=2.34' 'optdepend = upower: the battery readout' \
    'optdepend = curl: bookmark icons')" \
  "$(cat "$OUT/.PKGINFO")"

echo "the package is otherwise unchanged"
expect "the same entries, in the same order" \
  "usr/ usr/bin/ usr/bin/domicile .PKGINFO .MTREE .INSTALL" \
  "$(tar --zstd -tf "$PACKAGE" | tr '\n' ' ' | sed 's/ $//')"
expect "owned by root" "0/0" \
  "$(tar --zstd -tvf "$PACKAGE" --numeric-owner | awk '{print $2}' | sort -u)"
cmp -s "$TREE/usr/bin/domicile" "$OUT/usr/bin/domicile" &&
  [ "$(stat -c %a "$OUT/usr/bin/domicile")" = 755 ] &&
  ok "with the same files" ||
  fail "with the same files" "usr/bin/domicile changed"

echo "the file list describes the new .PKGINFO"
TREE="$OUT"
expect ".MTREE's .PKGINFO line" "$(mtree_line .PKGINFO)" \
  "$(gzip -dc "$OUT/.MTREE" | grep '^\./\.PKGINFO ')"
expect "and only that line changed" "$(mtree_line usr/bin/domicile)" \
  "$(gzip -dc "$OUT/.MTREE" | grep '^\./usr/bin/domicile ')"

if [ "$FAILED" -gt 0 ]; then
  echo "$FAILED failed"
  exit 1
fi
echo "all ok"
